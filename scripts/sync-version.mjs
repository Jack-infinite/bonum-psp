// Writes each published package's version into src/version.ts, so runtime code never has to
// read package.json (the SDK must run where there is no file system, e.g. Cloudflare Workers).
// Runs as part of `pnpm build` and of the Changesets version step; a unit test catches drift.
import { readFile, writeFile } from 'node:fs/promises';

const packages = [
  { dir: 'packages/sdk', name: 'bonum-psp' },
  { dir: 'packages/mcp', name: 'bonum-psp-mcp' },
];

for (const { dir, name } of packages) {
  const manifest = JSON.parse(
    await readFile(new URL(`../${dir}/package.json`, import.meta.url), 'utf8'),
  );
  const target = new URL(`../${dir}/src/version.ts`, import.meta.url);
  const source = [
    '// Generated by scripts/sync-version.mjs from package.json — do not edit by hand.',
    '',
    '/**',
    ` * The version of \`${name}\` you are running.`,
    ' *',
    ' * @example',
    ' * ```ts',
    ` * console.error(\`${name} \${VERSION}\`);`,
    ' * ```',
    ' */',
    `export const VERSION: string = '${manifest.version}';`,
    '',
  ].join('\n');
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current !== source) {
    await writeFile(target, source);
  }
}
